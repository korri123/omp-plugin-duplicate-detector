import { afterAll, beforeAll, describe, expect, it } from "bun:test";
import * as fs from "node:fs/promises";
import * as os from "node:os";
import * as path from "node:path";
import {
	createPathClassifier,
	isGeneratedContent,
	MAX_FILE_BYTES,
	readSourceFile,
	resolveRepoRoot,
	streamGitPaths,
	toRepoRelative,
} from "../src/detector/files";
import type { DetectorOptions } from "../src/types";

const baseOptions: DetectorOptions = {
	minTokens: 50,
	minLines: 5,
	ignorePatterns: [],
	ignoreTests: true,
	customTestPatterns: [],
	excludeTestPatterns: [],
	maxIndexedFiles: 10_000,
};

function git(cwd: string, ...args: string[]): void {
	const result = Bun.spawnSync(["git", ...args], { cwd });
	if (result.exitCode !== 0) {
		throw new Error(`git ${args.join(" ")}: ${result.stderr.toString()}`);
	}
}

async function put(root: string, rel: string, content: string): Promise<void> {
	const abs = path.join(root, rel);
	await fs.mkdir(path.dirname(abs), { recursive: true });
	await fs.writeFile(abs, content);
}

async function candidates(
	root: string,
	options: Partial<DetectorOptions> = {},
): Promise<string[]> {
	const classify = createPathClassifier({ ...baseOptions, ...options });
	const out: string[] = [];
	for await (const paths of streamGitPaths(root)) {
		for (const rel of paths) {
			if (classify(rel).format !== undefined) out.push(rel);
		}
	}
	return out.sort();
}

let root: string;
let outside: string;

beforeAll(async () => {
	root = await fs.realpath(
		await fs.mkdtemp(path.join(os.tmpdir(), "dd-files-")),
	);
	outside = await fs.realpath(
		await fs.mkdtemp(path.join(os.tmpdir(), "dd-files-outside-")),
	);
	git(root, "init", "-q");
	await put(root, ".gitignore", "secret.ts\nlogs/\n");
	await put(root, "src/app.ts", "export const app = 1;\n");
	await put(root, "src/app.test.ts", "export const appTest = 1;\n");
	await put(root, "src/thing.gen.ts", "export const gen = 1;\n");
	await put(root, "src/scratch.tmp.ts", "export const tmp = 1;\n");
	await put(root, "src/keep.ts", "export const keep = 1;\n");
	await put(root, "secret.ts", "export const secret = 1;\n");
	await put(root, "logs/trace.ts", "export const trace = 1;\n");
	await put(root, "target/debug/build/out.rs", "fn main() {}\n");
	await put(root, "crates/core/target/release/lib.rs", "fn lib() {}\n");
	await put(root, "node_modules/pkg/index.js", "module.exports = 1;\n");
	await put(root, "packages/web/node_modules/dep/index.js", "exports.a = 1;\n");
	await put(root, "space dir /trailing.ts", "export const t = 1;\n");
	await put(root, " leading.ts", "export const l = 1;\n");
	await put(root, "README.md", "# readme\n");
	await put(root, "big.ts", `// big\n${"x".repeat(MAX_FILE_BYTES + 10)}\n`);
	await put(
		root,
		"gen.ts",
		"// Code generated by protoc. @generated\nexport const g = 1;\n",
	);
	await put(root, "dist/bundle.js", "var bundled = 1;\n");
	git(root, "add", "src/app.ts", ".gitignore");
	// Tracked file inside a default-ignored directory.
	git(root, "add", "-f", "dist/bundle.js");
});

afterAll(async () => {
	await fs.rm(root, { recursive: true, force: true });
	await fs.rm(outside, { recursive: true, force: true });
});

describe("candidate enumeration", () => {
	it("lists tracked and untracked code files, excluding ignored, vendored, build, and test paths", async () => {
		expect(await candidates(root)).toEqual(
			[
				" leading.ts",
				"big.ts",
				"gen.ts",
				"space dir /trailing.ts",
				"src/app.ts",
				"src/keep.ts",
				"src/scratch.tmp.ts",
				"src/thing.gen.ts",
			].sort(),
		);
	});

	it("includes tests when ignoreTests is false", async () => {
		expect(await candidates(root, { ignoreTests: false })).toContain(
			"src/app.test.ts",
		);
	});

	it("applies brace-glob ignore patterns", async () => {
		const list = await candidates(root, {
			ignorePatterns: ["**/*.{gen,tmp}.ts"],
		});
		expect(list).not.toContain("src/thing.gen.ts");
		expect(list).not.toContain("src/scratch.tmp.ts");
		expect(list).toContain("src/keep.ts");
	});

	it("honours custom and excluded test patterns", async () => {
		const list = await candidates(root, {
			customTestPatterns: ["src/{keep,app}.ts"],
			excludeTestPatterns: ["src/app.test.ts"],
		});
		expect(list).not.toContain("src/keep.ts");
		expect(list).not.toContain("src/app.ts");
		expect(list).toContain("src/app.test.ts");
	});
});

describe("path classification for mutations", () => {
	it("reports the skip reason", () => {
		const classify = createPathClassifier(baseOptions);
		expect(classify("src/app.ts")).toEqual({ format: "typescript" });
		expect(classify("README.md")).toEqual({ skip: "unsupported-format" });
		expect(classify("target/debug/out.rs")).toEqual({ skip: "ignored" });
		expect(classify("a/node_modules/b/c.js")).toEqual({ skip: "ignored" });
		expect(classify("src/app.test.ts")).toEqual({ skip: "ignored" });
		expect(classify("vendor/lib.min.js")).toEqual({ skip: "ignored" });
		expect(classify("lib.min.js")).toEqual({ skip: "ignored" });
	});
});

describe("generated detection", () => {
	it("flags markers in header comments only", () => {
		expect(
			isGeneratedContent(
				"// Code generated by protoc. DO NOT EDIT.\npackage x\n",
			),
		).toBe(true);
		expect(
			isGeneratedContent("/*\n * Generated by OpenAPI.\n */\nexport {}\n"),
		).toBe(true);
		expect(isGeneratedContent('"""\nAutogenerated module.\n"""\nx = 1\n')).toBe(
			true,
		);
		expect(isGeneratedContent("# @generated\nx = 1\n")).toBe(true);
		expect(
			isGeneratedContent("const marker = /@generated/;\nexport {};\n"),
		).toBe(false);
		expect(
			isGeneratedContent(`${"// filler\n".repeat(300)}// @generated\n`),
		).toBe(false);
	});
});

describe("reading candidates", () => {
	it("skips files over the size cap and generated files", async () => {
		expect((await readSourceFile(path.join(root, "big.ts"))).skip).toBe(
			"too-large",
		);
		expect((await readSourceFile(path.join(root, "gen.ts"))).skip).toBe(
			"generated",
		);
		expect((await readSourceFile(path.join(root, "nope.ts"))).skip).toBe(
			"deleted",
		);
		const read = await readSourceFile(
			path.join(root, "space dir /trailing.ts"),
		);
		expect(read.skip).toBeUndefined();
		expect(read.skip === undefined && read.content).toBe(
			"export const t = 1;\n",
		);
	});
});

describe("repository root", () => {
	it("resolves the canonical toplevel from a subdirectory", async () => {
		expect(await resolveRepoRoot(path.join(root, "src"))).toEqual({ root });
	});

	it("reports non-git directories as unavailable", async () => {
		const result = await resolveRepoRoot(outside);
		expect(result.root).toBeUndefined();
		expect(result.unavailable).toBeString();
	});

	it("maps absolute paths to repo-relative POSIX paths", () => {
		expect(toRepoRelative(root, path.join(root, "src/new.ts"))).toBe(
			"src/new.ts",
		);
		expect(
			toRepoRelative(root, path.join(root, "space dir /trailing.ts")),
		).toBe("space dir /trailing.ts");
		expect(toRepoRelative(root, path.join(outside, "x.ts"))).toBeUndefined();
	});

	it("resolves symlinked spellings of paths inside the repo", async () => {
		const link = path.join(outside, "repo-link");
		await fs.symlink(root, link);
		expect(toRepoRelative(root, path.join(link, "src/app.ts"))).toBe(
			"src/app.ts",
		);
		expect(toRepoRelative(root, path.join(link, "src/missing/new.ts"))).toBe(
			"src/missing/new.ts",
		);
	});
});
