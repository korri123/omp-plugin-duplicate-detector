/** Files larger than this are never tokenized (jscpd's default cap). */
export const MAX_FILE_BYTES = 100 * 1024;

/** Bound on `git rev-parse` so a wedged git never hangs workspace setup. */
const GIT_ROOT_TIMEOUT_MS = 10_000;

/**
 * Build output, dependency, cache, and VCS directories. Excluded at any depth
 * even when the repository does not gitignore them.
 */
const DEFAULT_IGNORED_DIRS: ReadonlySet<string> = new Set([
	".git",
	".hg",
	".svn",
	"node_modules",
	"bower_components",
	"jspm_packages",
	"target",
	"dist",
	"build",
	"out",
	".next",
	".nuxt",
	".svelte-kit",
	".output",
	".turbo",
	".parcel-cache",
	".cache",
	".angular",
	".expo",
	"storybook-static",
	"vendor",
	"coverage",
	".nyc_output",
	"__pycache__",
	".venv",
	"venv",
	".tox",
	".mypy_cache",
	".pytest_cache",
	".gradle",
	".dart_tool",
	"elm-stuff",
	"Pods",
	"DerivedData",
	".terraform",
]);

/** Lockfiles, minified bundles, source maps, designer/generated files. */
const DEFAULT_NOISE_PATTERNS = [
	"*.lock",
	"*.lockb",
	"*-lock.json",
	"*-lock.yaml",
	"*-lock.yml",
	"*.lock.json",
	"*.min.*",
	"*.bundle.js",
	"*.map",
	"*.generated.*",
	"*.designer.cs",
	"*.designer.vb",
	".DS_Store",
];

/** Code-generation markers looked for in the leading comments of a file. */
const GENERATED_MARKER =
	/@generated\b|\bauto-?generated\b|\bautomatically generated\b|\bGENERATED BY\b|\bDO NOT (?:EDIT|MODIFY)\b|<auto-?generated\b/i;
/** Line-comment openers across languages (`*` covers block-comment bodies). */
const LINE_COMMENT = /^(?:\/\/|\*|#|--|;|%)/;
/** Block-comment / doc-string openers and their closers. */
const BLOCK_COMMENTS: readonly [open: string, close: string][] = [
	["/*", "*/"],
	['"""', '"""'],
	["'''", "'''"],
	["<!--", "-->"],
	["(*", "*)"],
];
const GENERATED_HEADER_CHARS = 2048;

/** Git environment variables that would redirect git away from `cwd`. */
const GIT_REDIRECT_ENV = [
	"GIT_DIR",
	"GIT_WORK_TREE",
	"GIT_INDEX_FILE",
	"GIT_COMMON_DIR",
	"GIT_PREFIX",
	"GIT_NAMESPACE",
];

function gitEnv(): Record<string, string | undefined> {
	const env: Record<string, string | undefined> = {
		...process.env,
		GIT_OPTIONAL_LOCKS: "0",
	};
	for (const key of GIT_REDIRECT_ENV) delete env[key];
	return env;
}

type RepoRoot =
	| { root: string; unavailable?: undefined }
	| { root?: undefined; unavailable: string };

/**
 * Canonical git toplevel containing `cwd`, or the reason none is available
 * (not a git work tree, missing directory, git not installed, timeout).
 */
export async function resolveRepoRoot(cwd: string): Promise<RepoRoot> {
	let dir: string;
	try {
		dir = await fs.realpath(cwd);
	} catch {
		return { unavailable: `Directory does not exist: ${cwd}` };
	}
	let proc: Bun.Subprocess<"ignore", "pipe", "pipe">;
	try {
		proc = Bun.spawn(["git", "rev-parse", "--show-toplevel"], {
			cwd: dir,
			env: gitEnv(),
			stdin: "ignore",
			stdout: "pipe",
			stderr: "pipe",
		});
	} catch (error) {
		return { unavailable: `Cannot run git: ${errorMessage(error)}` };
	}
	const timer = setTimeout(() => proc.kill(), GIT_ROOT_TIMEOUT_MS);
	try {
		const [stdout, stderr, code] = await Promise.all([
			new Response(proc.stdout).text(),
			new Response(proc.stderr).text(),
			proc.exited,
		]);
		if (proc.signalCode) {
			return { unavailable: "git rev-parse timed out" };
		}
		if (code !== 0) {
			const reason = stderr.trim().split("\n")[0] || `exit code ${code}`;
			return { unavailable: `Not a git work tree: ${reason}` };
		}
		// Strip only the line terminator: toplevel paths may end in spaces.
		const top = stdout.endsWith("\n") ? stdout.slice(0, -1) : stdout;
		if (!top) return { unavailable: "Not a git work tree" };
		return { root: await fs.realpath(top) };
	} catch (error) {
		return { unavailable: `git rev-parse failed: ${errorMessage(error)}` };
	} finally {
		clearTimeout(timer);
	}
}

/**
 * Streams every path git considers part of the work tree (tracked plus
 * untracked non-ignored), repo-relative POSIX, in chunks. Default build/vendor
 * directories are pruned inside git so it never walks huge untracked trees.
 * The output is parsed incrementally; it is never buffered whole.
 */
export async function* streamGitPaths(
	root: string,
	signal?: AbortSignal,
): AsyncGenerator<string[]> {
	signal?.throwIfAborted();
	const args = [
		"git",
		"ls-files",
		"-z",
		"--cached",
		"--others",
		"--exclude-standard",
	];
	for (const dir of DEFAULT_IGNORED_DIRS) args.push(`--exclude=${dir}/`);
	const proc = Bun.spawn(args, {
		cwd: root,
		env: gitEnv(),
		stdin: "ignore",
		stdout: "pipe",
		stderr: "pipe",
	});
	const kill = () => proc.kill();
	signal?.addEventListener("abort", kill, { once: true });
	const stderr = new Response(proc.stderr).text();
	const decoder = new TextDecoder();
	let pending: Uint8Array | undefined;
	let finished = false;
	try {
		for await (const chunk of proc.stdout) {
			const paths: string[] = [];
			let start = 0;
			let nul = chunk.indexOf(0);
			while (nul !== -1) {
				let bytes: Uint8Array = chunk.subarray(start, nul);
				if (pending) {
					bytes = concatBytes(pending, bytes);
					pending = undefined;
				}
				if (bytes.length > 0) paths.push(decoder.decode(bytes));
				start = nul + 1;
				nul = chunk.indexOf(0, start);
			}
			if (start < chunk.length) {
				const rest = chunk.subarray(start);
				pending = pending ? concatBytes(pending, rest) : rest.slice();
			}
			if (paths.length > 0) yield paths;
		}
		if (pending && pending.length > 0) yield [decoder.decode(pending)];
		const code = await proc.exited;
		signal?.throwIfAborted();
		if (code !== 0) {
			const reason = (await stderr).trim().split("\n")[0];
			throw new Error(
				`git ls-files failed (exit ${code})${reason ? `: ${reason}` : ""}`,
			);
		}
		finished = true;
	} finally {
		signal?.removeEventListener("abort", kill);
		if (!finished) proc.kill();
	}
}

function concatBytes(a: Uint8Array, b: Uint8Array): Uint8Array {
	const out = new Uint8Array(a.length + b.length);
	out.set(a, 0);
	out.set(b, a.length);
	return out;
}

/** Path-level verdict: the jscpd format, or why the path is never indexed. */
type PathVerdict =
	| { format: string; skip?: undefined }
	| { format?: undefined; skip: "ignored" | "unsupported-format" };

export type PathClassifier = (relPath: string) => PathVerdict;

const IGNORED: PathVerdict = { skip: "ignored" };
const UNSUPPORTED: PathVerdict = { skip: "unsupported-format" };

type FilterOptions = Pick<
	DetectorOptions,
	| "ignorePatterns"
	| "ignoreTests"
	| "customTestPatterns"
	| "excludeTestPatterns"
	| "formatsExts"
>;

/**
 * Builds the path filter shared by scans and mutation checks. Applied before
 * any filesystem access. `relPath` is repo-relative POSIX; it is used
 * verbatim (no trimming).
 */
export function createPathClassifier(options: FilterOptions): PathClassifier {
	const patterns = ignore()
		.add(DEFAULT_NOISE_PATTERNS)
		.add(expandBracePatterns(options.ignorePatterns));
	const isTest = createTestFilter({
		ignoreTests: options.ignoreTests,
		customTestPatterns: expandBracePatterns(options.customTestPatterns),
		excludeTestPatterns: expandBracePatterns(options.excludeTestPatterns),
	});
	const formatsExts = options.formatsExts;
	return (relPath) => {
		if (!isRepoRelative(relPath)) return IGNORED;
		let segStart = 0;
		for (
			let slash = relPath.indexOf("/");
			slash !== -1;
			slash = relPath.indexOf("/", segStart)
		) {
			if (DEFAULT_IGNORED_DIRS.has(relPath.slice(segStart, slash))) {
				return IGNORED;
			}
			segStart = slash + 1;
		}
		const format = detectFormat(relPath, formatsExts);
		if (!format) return UNSUPPORTED;
		try {
			if (patterns.ignores(relPath) || isTest(relPath)) return IGNORED;
		} catch {
			// `ignore` rejects names like "..."; never index what it cannot match.
			return IGNORED;
		}
		return { format };
	};
}

function isRepoRelative(relPath: string): boolean {
	return (
		relPath.length > 0 &&
		relPath !== "." &&
		relPath !== ".." &&
		!relPath.startsWith("/") &&
		!relPath.startsWith("./") &&
		!relPath.startsWith("../") &&
		!relPath.endsWith("/")
	);
}

/**
 * Expands `{a,b}` alternations (nested allowed, `\{` escapes respected) so
 * glob-style patterns work with gitignore matching, which has no braces.
 */
function expandBracePatterns(
	patterns: readonly string[] | undefined,
): string[] {
	const out: string[] = [];
	for (const pattern of patterns ?? []) {
		if (typeof pattern !== "string" || pattern.length === 0) continue;
		for (const expanded of expandBraces(pattern)) out.push(expanded);
	}
	return out;
}

function expandBraces(pattern: string): string[] {
	let depth = 0;
	let open = -1;
	const commas: number[] = [];
	for (let i = 0; i < pattern.length; i++) {
		const ch = pattern[i];
		if (ch === "\\") {
			i++;
			continue;
		}
		if (ch === "{") {
			if (depth === 0) {
				open = i;
				commas.length = 0;
			}
			depth++;
		} else if (ch === "}" && depth > 0) {
			depth--;
			if (depth === 0) {
				if (commas.length === 0) {
					open = -1;
					continue;
				}
				const head = pattern.slice(0, open);
				const tail = pattern.slice(i + 1);
				const result: string[] = [];
				let from = open + 1;
				for (const end of [...commas, i]) {
					const alt = pattern.slice(from, end);
					for (const expanded of expandBraces(head + alt + tail)) {
						result.push(expanded);
					}
					from = end + 1;
				}
				return result;
			}
		} else if (ch === "," && depth === 1) {
			commas.push(i);
		}
	}
	return [pattern];
}

/** Content-level skip: size cap and code-generation header markers. */
export function contentSkipReason(
	content: string,
): "too-large" | "generated" | undefined {
	if (Buffer.byteLength(content, "utf8") > MAX_FILE_BYTES) return "too-large";
	if (isGeneratedContent(content)) return "generated";
	return undefined;
}

/** True when a comment within the first 2 KiB carries a code-generation marker. */
export function isGeneratedContent(content: string): boolean {
	const head =
		content.length > GENERATED_HEADER_CHARS
			? content.slice(0, GENERATED_HEADER_CHARS)
			: content;
	let closer: string | undefined;
	for (const line of head.split("\n")) {
		const trimmed = line.trimStart();
		let comment = closer !== undefined;
		if (closer !== undefined) {
			if (line.includes(closer)) closer = undefined;
		} else {
			const block = BLOCK_COMMENTS.find(([open]) => trimmed.startsWith(open));
			if (block) {
				comment = true;
				if (!trimmed.includes(block[1], block[0].length)) closer = block[1];
			} else {
				comment = LINE_COMMENT.test(trimmed);
			}
		}
		if (comment && GENERATED_MARKER.test(line)) return true;
	}
	return false;
}

export interface FileStat {
	size: number;
	mtimeMs: number;
}

/** Size + mtime of a regular file, or undefined when missing / not a file. */
export async function statFile(absPath: string): Promise<FileStat | undefined> {
	try {
		const st = await fs.stat(absPath);
		if (!st.isFile()) return undefined;
		return { size: st.size, mtimeMs: st.mtimeMs };
	} catch (error) {
		if (isMissing(error)) return undefined;
		throw error;
	}
}

type SourceRead =
	| { content: string; stat: FileStat; skip?: undefined }
	| { skip: "deleted" | "too-large" | "generated"; stat?: FileStat };

/**
 * Reads a candidate source file, applying the size cap before reading and
 * the generated-header check after. Throws only for unexpected I/O errors.
 */
export async function readSourceFile(
	absPath: string,
	known?: FileStat,
): Promise<SourceRead> {
	const stat = known ?? (await statFile(absPath));
	if (!stat) return { skip: "deleted" };
	if (stat.size > MAX_FILE_BYTES) return { skip: "too-large", stat };
	let bytes: Buffer;
	try {
		bytes = await fs.readFile(absPath);
	} catch (error) {
		if (isMissing(error)) return { skip: "deleted" };
		throw error;
	}
	if (bytes.length > MAX_FILE_BYTES) return { skip: "too-large", stat };
	const content = bytes.toString("utf8");
	if (isGeneratedContent(content)) return { skip: "generated", stat };
	return { content, stat };
}

/**
 * Repo-relative POSIX path for an absolute path, resolving symlinks in the
 * longest existing prefix (the file itself may be deleted). Undefined when
 * the path is outside `root`. Synchronous so a check can resolve its path
 * (and snapshot the indexed pre-image) in the same tick it is queued.
 */
export function toRepoRelative(
	root: string,
	absPath: string,
): string | undefined {
	const canonical = canonicalize(path.resolve(root, absPath));
	const rel = path.relative(root, canonical);
	if (
		!rel ||
		rel === ".." ||
		rel.startsWith(`..${path.sep}`) ||
		path.isAbsolute(rel)
	) {
		return undefined;
	}
	return path.sep === "/" ? rel : rel.split(path.sep).join("/");
}

function canonicalize(resolved: string): string {
	let current = resolved;
	let suffix = "";
	for (;;) {
		try {
			const real = realpathSync(current);
			return suffix ? path.join(real, suffix) : real;
		} catch {
			const parent = path.dirname(current);
			if (parent === current) return resolved;
			suffix = suffix
				? path.join(path.basename(current), suffix)
				: path.basename(current);
			current = parent;
		}
	}
}

function isMissing(error: unknown): boolean {
	const code = (error as NodeJS.ErrnoException | undefined)?.code;
	return code === "ENOENT" || code === "ENOTDIR";
}

export function errorMessage(error: unknown): string {
	return error instanceof Error ? error.message : String(error);
}
